export interface ExportedProject {
  files: { path: string; content: string }[];
}

export function exportProject(components: Component[]): ExportedProject {
  return {
    files: [
      { path: "app/page.tsx", content: generatePageCode(components) },
      { path: "app/layout.tsx", content: generateLayoutCode() },
      { path: "app/globals.css", content: generateGlobalsCss() },
      { path: "package.json", content: generatePackageJson() },
      { path: "next.config.ts", content: generateNextConfig() },
      { path: "lingo.config.ts", content: generateLingoConfig() },
      { path: "tsconfig.json", content: generateTsConfig() },
      { path: "postcss.config.mjs", content: generatePostcssConfig() },
    ],
  };
}
