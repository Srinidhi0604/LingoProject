import { Component, ComponentType, DEFAULT_PROPS } from "@/types/intent";

function propsToJsx(props: Record<string, unknown>): string {
  const entries = Object.entries(props);
  if (entries.length === 0) return "";

  const propsStr = entries
    .filter(([key]) => key !== "children")
    .map(([key, value]) => {
      if (key === "className") return ` className="${value}"`;
      if (key === "text") return "";
      if (typeof value === "string") return ` ${key}="${value}"`;
      if (typeof value === "number") return ` ${key}={${value}}`;
      if (typeof value === "boolean") return value ? ` ${key}` : "";
      return ` ${key}={${JSON.stringify(value)}}`;
    })
    .join("");

  return propsStr;
}

function componentToJsx(component: Component, indent: number = 2): string {
  const spaces = " ".repeat(indent);
  const { type, props, children } = component;
  const propsStr = propsToJsx(props || {});

  const textContent = props?.text as string | undefined;
  const hasChildren = children && children.length > 0;
  const hasText = textContent && !hasChildren;

  switch (type) {
    case "input":
    case "checkbox":
    case "radio":
      return `${spaces}<${type}${propsStr} />`;

    case "image":
      return `${spaces}<img${propsStr} />`;

    case "heading": {
      const level = props?.level || 1;
      const Tag = `h${level}`;
      if (hasChildren) {
        const childrenJsx = children.map((c) => componentToJsx(c, indent + 2)).join("\n");
        return `${spaces}<${Tag}${propsStr}>\n${childrenJsx}\n${spaces}</${Tag}>`;
      }
      return `${spaces}<${Tag}${propsStr}>${hasText ? textContent : ""}</${Tag}>`;
    }

    default: {
      const Tag = type === "text" ? "span" : type === "paragraph" ? "p" : type;
      if (hasChildren) {
        const childrenJsx = children.map((c) => componentToJsx(c, indent + 2)).join("\n");
        return `${spaces}<${Tag}${propsStr}>\n${childrenJsx}\n${spaces}</${Tag}>`;
      }
      if (hasText) {
        return `${spaces}<${Tag}${propsStr}>${textContent}</${Tag}>`;
      }
      return `${spaces}<${Tag}${propsStr} />`;
    }
  }
}

export function generatePageCode(components: Component[]): string {
  const componentsJsx = components.map((c) => componentToJsx(c, 4)).join("\n");

  return `export default function Page() {
  return (
    <div className="flex min-h-screen flex-col items-center justify-center p-8">
${componentsJsx || '      <p className="text-lg">No components yet</p>'}
    </div>
  );
}
`;
}

